function isHiddenLibraryResource(resource: LibraryResource) {
  const haystack = `${resource.title} ${resource.description} ${resource.source} ${resource.url} ${resource.topics.join(" ")}`.toLowerCase()
  const isYoutube = haystack.includes("youtube.com") || haystack.includes("youtu.be")
  const isTimketMezmur = (haystack.includes("timket") || resource.title.includes("ጥምቀት")) &&
    (haystack.includes("mezmur") || haystack.includes("hymn") || resource.title.includes("መዝሙር"))

  return isYoutube || isTimketMezmur
}

